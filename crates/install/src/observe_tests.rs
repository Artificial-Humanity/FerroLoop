fn clean() -> BuildInfo {
    BuildInfo::from_stamp("0.1.0", C, "false", "1", None)
}

fn status(r: &DoctorReport, id: &str) -> CheckStatus {
    r.check(id)
        .unwrap_or_else(|| panic!("no check {id}"))
        .status
}

fn detail(r: &DoctorReport, id: &str) -> String {
    r.check(id).unwrap().detail.clone()
}

fn receipt() -> InstallReceipt {
    InstallReceipt {
        schema_version: RECEIPT_SCHEMA_VERSION,
        release: ReceiptRelease {
            version: "0.1.0".into(),
            name: "0.1.0+0123456789ab".into(),
            kind: ReleaseKind::SourceBuild,
            commit: Some(C.into()),
        },
        profile: Profile::Full,
        products: vec![Product::Ferroloop],
        layout: ReceiptLayout {
            prefix: "/i/share/fl".into(),
            bin_dir: "/i/bin".into(),
            unit_dir: "/i/units".into(),
        },
        artifacts: vec![],
        paths: vec![],
        aliases: vec![],
        units: vec![],
        catalog_entries: vec![],
        config_blocks: vec![],
        journal: vec![],
    }
}

use sha2::{Digest, Sha256};
use std::collections::BTreeMap;
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};
use std::time::Duration;

fn sha(bytes: &[u8]) -> String {
    format!("{:x}", Sha256::digest(bytes))
}

/// Every entry under `root` (relative path, kind, mode, length, mtime, content hash,
/// link target): equal before and after proves nothing was written.
fn tree(root: &Path) -> BTreeMap<String, String> {
    fn walk(dir: &Path, root: &Path, out: &mut BTreeMap<String, String>) {
        for e in std::fs::read_dir(dir).unwrap() {
            let e = e.unwrap();
            let p = e.path();
            let meta = std::fs::symlink_metadata(&p).unwrap();
            let rel = p.strip_prefix(root).unwrap().display().to_string();
            let extra = if meta.file_type().is_symlink() {
                std::fs::read_link(&p).unwrap().display().to_string()
            } else if meta.is_file() {
                sha(&std::fs::read(&p).unwrap())
            } else {
                String::new()
            };
            out.insert(
                rel,
                format!(
                    "{:?} {:o} {} {:?} {extra}",
                    meta.file_type(),
                    meta.permissions().mode(),
                    meta.len(),
                    meta.modified().unwrap()
                ),
            );
            if meta.is_dir() {
                walk(&p, root, out);
            }
        }
    }
    let mut out = BTreeMap::new();
    walk(root, root, &mut out);
    out
}

struct Fixture {
    _tmp: tempfile::TempDir,
    root: PathBuf,
}

/// A real install under `<root>`: a release dir with a binary, `current`, the launcher,
/// an alias, a unit and the receipt that describes them.
fn install() -> Fixture {
    let tmp = tempfile::tempdir().unwrap();
    let root = tmp.path().to_path_buf();
    let prefix = root.join(".local/share/fl");
    let rel = prefix.join("releases/0.1.0+0123456789ab");
    std::fs::create_dir_all(rel.join("bin")).unwrap();
    std::fs::create_dir_all(root.join(".local/bin")).unwrap();
    std::fs::create_dir_all(root.join(".config/systemd/user")).unwrap();
    let bin = b"#!/bin/true\nfl binary";
    std::fs::write(rel.join("bin/fl"), bin).unwrap();
    std::os::unix::fs::symlink("releases/0.1.0+0123456789ab", prefix.join("current")).unwrap();
    std::os::unix::fs::symlink(prefix.join("current/bin/fl"), root.join(".local/bin/fl")).unwrap();
    std::os::unix::fs::symlink("fl", root.join(".local/bin/agent-msg")).unwrap();
    let unit = b"# generated by fl install 0.1.0+0123456789ab\n[Service]\nExecStart=fl\n";
    std::fs::write(root.join(".config/systemd/user/ferrowire.service"), unit).unwrap();
    let s = |p: &Path| p.display().to_string();
    let mut r = receipt();
    r.layout = ReceiptLayout {
        prefix: s(&prefix),
        bin_dir: s(&root.join(".local/bin")),
        unit_dir: s(&root.join(".config/systemd/user")),
    };
    r.paths = vec![
        OwnedPath {
            path: s(&rel),
            kind: OwnedPathKind::Dir,
            sha256: None,
            link_target: None,
        },
        OwnedPath {
            path: s(&rel.join("bin/fl")),
            kind: OwnedPathKind::File,
            sha256: Some(sha(bin)),
            link_target: None,
        },
        OwnedPath {
            path: s(&prefix.join("current")),
            kind: OwnedPathKind::Symlink,
            sha256: None,
            link_target: Some("releases/0.1.0+0123456789ab".into()),
        },
        OwnedPath {
            path: s(&root.join(".local/bin/fl")),
            kind: OwnedPathKind::Symlink,
            sha256: None,
            link_target: Some(s(&prefix.join("current/bin/fl"))),
        },
    ];
    r.aliases = vec![OwnedAlias {
        name: "agent-msg".into(),
        path: s(&root.join(".local/bin/agent-msg")),
        target: "fl".into(),
    }];
    r.units = vec![OwnedUnit {
        name: "ferrowire.service".into(),
        path: s(&root.join(".config/systemd/user/ferrowire.service")),
        sha256: sha(unit),
        release: "0.1.0+0123456789ab".into(),
    }];
    std::fs::write(prefix.join("receipt.json"), r.to_json()).unwrap();
    Fixture { _tmp: tmp, root }
}

fn spec(root: &Path, stores: StoreFacts) -> Observe<'static> {
    Observe {
        binary: clean(),
        binary_name: "fl",
        home: Some(root.to_path_buf()),
        layout: Layout::under_root(root.to_str().unwrap()).unwrap(),
        ui_dir: UiDir::ReleaseCurrent,
        vault_path: root.join(".local/share/fl/vault.enc"),
        key_path: root.join(".config/fl/vault.key"),
        key_in_env: false,
        stores,
        budget: Duration::from_secs(30),
    }
}

#[test]
fn a_real_install_passes_and_the_tree_is_untouched() {
    let f = install();
    let before = tree(&f.root);
    let r = observe(spec(&f.root, StoreFacts::default()));
    assert_eq!(tree(&f.root), before, "observing wrote something");
    assert_eq!(
        status(&r, ids::RECEIPT_INTEGRITY),
        CheckStatus::Pass,
        "{}",
        detail(&r, ids::RECEIPT_INTEGRITY)
    );
    assert_eq!(
        status(&r, ids::PATH_OWNERSHIP),
        CheckStatus::Pass,
        "{}",
        detail(&r, ids::PATH_OWNERSHIP)
    );
    assert_eq!(status(&r, ids::RELEASE_IDENTITY), CheckStatus::Pass);
    // No store, no vault, no UI bundle here.
    assert_eq!(status(&r, ids::STORE_HEALTH), CheckStatus::NotInstalled);
    assert_eq!(status(&r, ids::VAULT_PERMS), CheckStatus::NotInstalled);
    assert_eq!(status(&r, ids::CODE_UI_AGREE), CheckStatus::NotInstalled);
}

#[test]
fn an_edited_owned_file_warns_and_a_missing_one_fails() {
    let f = install();
    let bin = f
        .root
        .join(".local/share/fl/releases/0.1.0+0123456789ab/bin/fl");
    std::fs::write(&bin, b"tampered").unwrap();
    let r = observe(spec(&f.root, StoreFacts::default()));
    assert_eq!(status(&r, ids::PATH_OWNERSHIP), CheckStatus::Warn);
    assert!(detail(&r, ids::PATH_OWNERSHIP).contains("bin/fl was edited"));
    std::fs::remove_file(&bin).unwrap();
    let r = observe(spec(&f.root, StoreFacts::default()));
    assert_eq!(status(&r, ids::PATH_OWNERSHIP), CheckStatus::Fail);
    assert!(detail(&r, ids::PATH_OWNERSHIP).contains("is missing"));
    assert_eq!(r.exit_code(), 1);
}

#[test]
fn a_corrupt_or_oversized_receipt_fails_and_is_not_unmanaged() {
    let f = install();
    let receipt = f.root.join(".local/share/fl/receipt.json");
    std::fs::write(&receipt, "{ not json").unwrap();
    let r = observe(spec(&f.root, StoreFacts::default()));
    assert_eq!(status(&r, ids::RECEIPT_INTEGRITY), CheckStatus::Fail);
    assert_eq!(status(&r, ids::PATH_OWNERSHIP), CheckStatus::Unsupported);
    // Oversized: refused unread.
    let big = std::fs::File::create(&receipt).unwrap();
    big.set_len(fl_core::install::MAX_RECEIPT_BYTES as u64 + 1)
        .unwrap();
    let r = observe(spec(&f.root, StoreFacts::default()));
    assert_eq!(status(&r, ids::RECEIPT_INTEGRITY), CheckStatus::Fail);
    assert!(detail(&r, ids::RECEIPT_INTEGRITY).contains("larger than"));
    // A directory where the receipt belongs, and a fifo.
    std::fs::remove_file(&receipt).unwrap();
    std::fs::create_dir(&receipt).unwrap();
    let r = observe(spec(&f.root, StoreFacts::default()));
    assert_eq!(status(&r, ids::RECEIPT_INTEGRITY), CheckStatus::Fail);
    std::fs::remove_dir(&receipt).unwrap();
    assert!(
        std::process::Command::new("mkfifo")
            .arg(&receipt)
            .status()
            .unwrap()
            .success()
    );
    let r = observe(spec(&f.root, StoreFacts::default()));
    assert_eq!(status(&r, ids::RECEIPT_INTEGRITY), CheckStatus::Fail);
}

#[test]
fn an_empty_root_is_unmanaged_everywhere() {
    let tmp = tempfile::tempdir().unwrap();
    let before = tree(tmp.path());
    let r = observe(spec(tmp.path(), StoreFacts::default()));
    assert_eq!(tree(tmp.path()), before);
    assert!(before.is_empty());
    for id in &CHECK_IDS[1..] {
        assert_eq!(status(&r, id), CheckStatus::NotInstalled, "{id}");
    }
    assert_eq!(r.exit_code(), 0);
}

#[test]
fn the_vault_is_judged_by_lstat_and_its_contents_are_never_read() {
    let tmp = tempfile::tempdir().unwrap();
    let root = tmp.path();
    let vault = root.join(".local/share/fl/vault.enc");
    let key = root.join(".config/fl/vault.key");
    std::fs::create_dir_all(vault.parent().unwrap()).unwrap();
    std::fs::create_dir_all(key.parent().unwrap()).unwrap();
    std::fs::write(&vault, "SENTINEL-VAULT-CONTENT").unwrap();
    std::fs::write(&key, "SENTINEL-KEY-CONTENT").unwrap();
    for p in [&vault, &key] {
        std::fs::set_permissions(p, std::fs::Permissions::from_mode(0o600)).unwrap();
    }
    for d in [vault.parent().unwrap(), key.parent().unwrap()] {
        std::fs::set_permissions(d, std::fs::Permissions::from_mode(0o700)).unwrap();
    }
    let before = tree(root);
    let r = observe(spec(root, StoreFacts::default()));
    assert_eq!(
        status(&r, ids::VAULT_PERMS),
        CheckStatus::Pass,
        "{}",
        detail(&r, ids::VAULT_PERMS)
    );
    let all = r.to_json() + &r.render_text();
    assert!(!all.contains("SENTINEL"), "{all}");
    assert_eq!(tree(root), before);

    // 0644 fails; a file nobody can read is still examined, not opened.
    std::fs::set_permissions(&key, std::fs::Permissions::from_mode(0o644)).unwrap();
    let r = observe(spec(root, StoreFacts::default()));
    assert_eq!(status(&r, ids::VAULT_PERMS), CheckStatus::Fail);
    assert!(detail(&r, ids::VAULT_PERMS).contains("0644"));
    std::fs::set_permissions(&key, std::fs::Permissions::from_mode(0o000)).unwrap();
    let r = observe(spec(root, StoreFacts::default()));
    assert_eq!(status(&r, ids::VAULT_PERMS), CheckStatus::Warn);
    assert!(!(r.to_json()).contains("SENTINEL"));
    // A symlink in place of the vault is refused, as FerroGate refuses it.
    std::fs::set_permissions(&key, std::fs::Permissions::from_mode(0o600)).unwrap();
    std::fs::remove_file(&vault).unwrap();
    std::os::unix::fs::symlink(&key, &vault).unwrap();
    let r = observe(spec(root, StoreFacts::default()));
    assert_eq!(status(&r, ids::VAULT_PERMS), CheckStatus::Fail);
    assert!(detail(&r, ids::VAULT_PERMS).contains("symlink"));
}

#[test]
fn the_ui_bundle_is_read_through_the_current_link() {
    let f = install();
    let dist = f
        .root
        .join(".local/share/fl/releases/0.1.0+0123456789ab/ui/dist");
    std::fs::create_dir_all(&dist).unwrap();
    // No build-info.json: unsupported.
    let r = observe(spec(&f.root, StoreFacts::default()));
    assert_eq!(status(&r, ids::CODE_UI_AGREE), CheckStatus::Unsupported);
    std::fs::write(
        dist.join("build-info.json"),
        json!({"commit": &C[..12], "dirty": false}).to_string(),
    )
    .unwrap();
    let r = observe(spec(&f.root, StoreFacts::default()));
    assert_eq!(
        status(&r, ids::CODE_UI_AGREE),
        CheckStatus::Pass,
        "{}",
        detail(&r, ids::CODE_UI_AGREE)
    );
    std::fs::write(
        dist.join("build-info.json"),
        json!({"commit": &OTHER_C[..12]}).to_string(),
    )
    .unwrap();
    let r = observe(spec(&f.root, StoreFacts::default()));
    assert_eq!(status(&r, ids::CODE_UI_AGREE), CheckStatus::Fail);
    // An explicit directory beats the release layout.
    let mut o = spec(&f.root, StoreFacts::default());
    o.ui_dir = UiDir::Explicit(f.root.join("elsewhere"));
    assert_eq!(
        status(&observe(o), ids::CODE_UI_AGREE),
        CheckStatus::NotInstalled
    );
}

#[test]
fn a_missing_home_makes_the_receipt_unlocatable_not_absent() {
    let mut o = spec(Path::new("/nonexistent-root-xyz"), StoreFacts::default());
    o.layout = Layout::user_default();
    o.home = None;
    let r = observe(o);
    assert_eq!(status(&r, ids::RECEIPT_INTEGRITY), CheckStatus::Unsupported);
    assert!(detail(&r, ids::RECEIPT_INTEGRITY).contains("HOME"));
}
