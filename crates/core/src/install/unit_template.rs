//! Service unit templates (#205 phase A4c): `contrib/units/<name>` in a release.
//!
//! A template is a unit file with three placeholders, filled in by whatever writes the unit
//! into the unit directory. NOTHING writes one in this release; the installer only stages the
//! templates inside the release directory and lists the registration as "not executed". This
//! module is the single definition of the placeholders, so the writer to come and the tests
//! agree on them.
//!
//! * `{{RELEASE}}` is the release directory name (`<version>+<sha12>`). It completes the first
//!   line of every template, `# generated by fl install {{RELEASE}}`, the marker the planner
//!   requires ([`UNIT_MARKER`]).
//! * `{{LAUNCHER}}` is the launcher path (`<bin_dir>/fl`, a symlink into `current`).
//! * `{{PREFIX}}` is the install prefix. `{{PREFIX}}/current/...` follows an upgrade.
//!
//! A placeholder is not `@NAME@`: systemd reads a leading `@` of an `ExecStart` as "set argv[0]".

use super::{UNIT_MARKER, fingerprint};
use std::fmt;

const PLACEHOLDERS: [&str; 3] = ["{{RELEASE}}", "{{LAUNCHER}}", "{{PREFIX}}"];

/// Why a template was not rendered.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum UnitRenderError {
    /// A value is not usable in a unit file.
    BadValue {
        name: &'static str,
        why: &'static str,
    },
    /// The template has a `{{...}}` that is not one of the three placeholders.
    UnknownPlaceholder(String),
    /// The rendered text has no marker line (the planner would call the file foreign).
    NoMarker,
}

impl fmt::Display for UnitRenderError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::BadValue { name, why } => write!(f, "{name} {why}"),
            Self::UnknownPlaceholder(s) => write!(f, "unknown placeholder near `{s}`"),
            Self::NoMarker => write!(f, "the unit has no `{UNIT_MARKER} <release>` line"),
        }
    }
}

impl std::error::Error for UnitRenderError {}

/// A path that stays ONE word in an `ExecStart` line and is not touched by systemd: absolute,
/// and without whitespace, a control character, a quote, a backslash, `%` (a specifier), `$`
/// (a variable) or a brace.
fn path_ok(name: &'static str, v: &str) -> Result<(), UnitRenderError> {
    let bad = |why| Err(UnitRenderError::BadValue { name, why });
    if !v.starts_with('/') {
        return bad("is not an absolute path");
    }
    if v.chars().any(|c| {
        c.is_whitespace()
            || c.is_control()
            || matches!(c, '"' | '\'' | '\\' | '%' | '$' | '{' | '}')
    }) {
        return bad("holds a character a unit file cannot carry in one word");
    }
    Ok(())
}

/// Fill the placeholders of `template`.
///
/// # Errors
/// A `release` that is not a single file name, a `launcher` or `prefix` that is not a plain
/// absolute path, a `{{...}}` left over, or a result with no marker line.
pub fn render_unit(
    template: &str,
    release: &str,
    launcher: &str,
    prefix: &str,
) -> Result<String, UnitRenderError> {
    if !super::file_name_ok(release) {
        return Err(UnitRenderError::BadValue {
            name: "release",
            why: "is not a plain release name",
        });
    }
    path_ok("launcher", launcher)?;
    path_ok("prefix", prefix)?;
    let out = template
        .replace(PLACEHOLDERS[0], release)
        .replace(PLACEHOLDERS[1], launcher)
        .replace(PLACEHOLDERS[2], prefix);
    if let Some(i) = out.find("{{") {
        let rest = &out[i..];
        let end = rest.char_indices().nth(24).map_or(rest.len(), |(n, _)| n);
        return Err(UnitRenderError::UnknownPlaceholder(rest[..end].to_string()));
    }
    if !fingerprint(out.as_bytes()).is_ok_and(|f| f.has_unit_marker) {
        return Err(UnitRenderError::NoMarker);
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::install::{FileKind, default_manifest};
    use std::collections::BTreeSet;

    /// Every template of the repository, as `(file name, text)`.
    const TEMPLATES: [(&str, &str); 4] = [
        (
            "ferrostore.service",
            include_str!("../../../../contrib/units/ferrostore.service"),
        ),
        (
            "ferrostore@.service",
            include_str!("../../../../contrib/units/ferrostore@.service"),
        ),
        (
            "ferrowire.service",
            include_str!("../../../../contrib/units/ferrowire.service"),
        ),
        (
            "ferroloop-hub.service",
            include_str!("../../../../contrib/units/ferroloop-hub.service"),
        ),
    ];

    fn key<'a>(text: &'a str, section: &str, name: &str) -> Vec<&'a str> {
        let mut inside = false;
        let mut out = Vec::new();
        for line in text.lines() {
            let t = line.trim();
            if t.starts_with('[') && t.ends_with(']') {
                inside = &t[1..t.len() - 1] == section;
            } else if inside && let Some(v) = t.strip_prefix(name).and_then(|r| r.strip_prefix('='))
            {
                out.push(v.trim());
            }
        }
        out
    }

    fn template(name: &str) -> &'static str {
        TEMPLATES.iter().find(|(n, _)| *n == name).unwrap().1
    }

    #[test]
    fn every_template_the_manifest_offers_exists_and_no_other_does() {
        let offered: BTreeSet<String> = default_manifest()
            .products
            .iter()
            .flat_map(|p| p.files.iter())
            .filter(|f| f.kind == FileKind::UnitTemplate)
            .filter_map(|f| f.path.strip_prefix("contrib/units/").map(str::to_string))
            .collect();
        let have: BTreeSet<String> = TEMPLATES.iter().map(|(n, _)| (*n).to_string()).collect();
        assert_eq!(offered, have);
    }

    #[test]
    fn a_template_has_the_marker_first_and_the_three_sections() {
        for (name, text) in TEMPLATES {
            assert_eq!(
                text.lines().next(),
                Some("# generated by fl install {{RELEASE}}"),
                "{name}"
            );
            let sections: Vec<&str> = text.lines().filter(|l| l.starts_with('[')).collect();
            assert_eq!(sections, ["[Unit]", "[Service]", "[Install]"], "{name}");
            assert_eq!(
                key(text, "Install", "WantedBy"),
                ["default.target"],
                "{name}"
            );
            assert_eq!(key(text, "Service", "Type"), ["simple"], "{name}");
            assert_eq!(key(text, "Service", "Restart"), ["on-failure"], "{name}");
            assert!(!key(text, "Unit", "Description").is_empty(), "{name}");
        }
    }

    #[test]
    fn a_template_is_single_line_clean_and_carries_no_secret_or_workstation_path() {
        for (name, text) in TEMPLATES {
            assert!(text.ends_with('\n') && !text.contains('\r') && !text.contains('\0'));
            assert!(!text.contains("Projects/"), "{name}: a workstation path");
            assert!(!text.contains("/home/"), "{name}");
            assert!(
                key(text, "Service", "WorkingDirectory").is_empty(),
                "{name}"
            );
            assert!(key(text, "Service", "EnvironmentFile").is_empty(), "{name}");
            for env in key(text, "Service", "Environment") {
                let lower = env.to_ascii_lowercase();
                for word in ["token", "secret", "key", "pass", "psk", "cred"] {
                    assert!(!lower.contains(word), "{name}: {env}");
                }
            }
            assert!(
                !text.contains("--token") && !text.contains("--psk"),
                "{name}"
            );
        }
    }

    #[test]
    fn the_exec_line_starts_with_the_launcher_or_the_installed_binary() {
        for (name, text) in TEMPLATES {
            let exec = key(text, "Service", "ExecStart");
            assert_eq!(exec.len(), 1, "{name}");
            assert!(
                exec[0].starts_with("{{LAUNCHER}} ")
                    || exec[0].starts_with("{{PREFIX}}/current/bin/ferrostore "),
                "{name}: {}",
                exec[0]
            );
        }
    }

    #[test]
    fn ordering_follows_the_spec() {
        let wire = template("ferrowire.service");
        assert_eq!(key(wire, "Unit", "PartOf"), ["ferrostore.service"]);
        assert_eq!(key(wire, "Unit", "After"), ["ferrostore.service"]);
        let hub = template("ferroloop-hub.service");
        for k in ["Wants", "After"] {
            let v = key(hub, "Unit", k);
            assert_eq!(v, ["ferrostore.service ferrowire.service"], "{k}");
        }
    }

    #[test]
    fn the_hub_is_given_the_installed_bundle_explicitly() {
        let exec = key(template("ferroloop-hub.service"), "Service", "ExecStart")[0];
        assert!(
            exec.ends_with(" --ui-dir {{PREFIX}}/current/ui/dist"),
            "{exec}"
        );
    }

    #[test]
    fn a_rendered_template_is_a_marked_unit_with_nothing_left_to_fill() {
        for (name, text) in TEMPLATES {
            let out = render_unit(text, "0.1.0+0123456789ab", "/i/bin/fl", "/i/share/fl").unwrap();
            assert!(!out.contains("{{") && !out.contains("}}"), "{name}");
            assert!(
                fingerprint(out.as_bytes()).unwrap().has_unit_marker,
                "{name}"
            );
            assert!(out.starts_with("# generated by fl install 0.1.0+0123456789ab\n"));
            let exec = key(&out, "Service", "ExecStart")[0].to_string();
            assert!(
                exec.starts_with("/i/bin/fl ") || exec.starts_with("/i/share/fl/current/bin/"),
                "{exec}"
            );
        }
        // the template alone is not a marked unit: its release is still a placeholder, but the
        // line is already the shape the planner looks for
        assert!(
            fingerprint(template("ferrowire.service").as_bytes())
                .unwrap()
                .has_unit_marker
        );
    }

    #[test]
    fn rendering_refuses_a_value_that_would_break_the_exec_line() {
        let t = template("ferroloop-hub.service");
        for bad in [
            "relative/fl",
            "/i/my bin/fl",
            "/i/bin/fl\n[Service]",
            "/i/%h/fl",
            "/i/$HOME/fl",
            "/i/\"fl",
            "/i/{{PREFIX}}/fl",
        ] {
            assert!(
                matches!(
                    render_unit(t, "0.1.0+a", bad, "/p"),
                    Err(UnitRenderError::BadValue {
                        name: "launcher",
                        ..
                    })
                ),
                "{bad:?}"
            );
            assert!(
                matches!(
                    render_unit(t, "0.1.0+a", "/l", bad),
                    Err(UnitRenderError::BadValue { name: "prefix", .. })
                ),
                "{bad:?}"
            );
        }
        for bad in ["", "a/b", "..", "a b", "a\nb"] {
            assert!(
                matches!(
                    render_unit(t, bad, "/l", "/p"),
                    Err(UnitRenderError::BadValue {
                        name: "release",
                        ..
                    })
                ),
                "{bad:?}"
            );
        }
        assert!(matches!(
            render_unit(
                "# generated by fl install {{RELEASE}}\n{{OTHER}}\n",
                "1",
                "/l",
                "/p"
            ),
            Err(UnitRenderError::UnknownPlaceholder(_))
        ));
        assert_eq!(
            render_unit("[Unit]\n", "1", "/l", "/p"),
            Err(UnitRenderError::NoMarker)
        );
    }
}
