/// What the user asked for.
#[derive(Debug, Clone)]
pub struct InstallRequest {
    pub profile: Option<Profile>,
    pub add: Vec<Product>,
    pub remove: Vec<Product>,
    pub layout: Layout,
    pub adopt: bool,
}

impl InstallRequest {
    /// Parse product ids typed on the command line.
    pub fn parse_products(ids: &[String]) -> Result<Vec<Product>, PlanError> {
        ids.iter()
            .map(|s| {
                Product::from_wire(s).ok_or_else(|| PlanError::UnknownProduct(display_trunc(s)))
            })
            .collect()
    }

    pub fn parse_profile(id: &str) -> Result<Profile, PlanError> {
        Profile::from_wire(id).ok_or_else(|| PlanError::UnknownProfile(display_trunc(id)))
    }
}

/// Why no plan was made.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum PlanError {
    #[error("unknown product `{0}` (accepted: {accepted})", accepted = Product::wire_values())]
    UnknownProduct(String),
    #[error("unknown profile `{0}` (accepted: {accepted})", accepted = Profile::wire_values())]
    UnknownProfile(String),
    #[error("`{0}` is both added and removed")]
    AddAndRemove(Product),
    #[error("{0}")]
    PrefixInvalid(String),
    #[error("`{0}` cannot be an install prefix: installs are per-user, never system-wide")]
    PrefixForbidden(String),
    #[error("--adopt is not implemented in this release")]
    AdoptNotImplemented,
    #[error("the manifest is invalid: {}", join_errors(.0))]
    InvalidManifest(Vec<ManifestError>),
    #[error("the manifest declares no `{0}` profile")]
    ProfileNotInManifest(Profile),
    #[error("the manifest does not declare product `{0}`")]
    NotInManifest(Product),
    #[error("`{0}` is required in every install and cannot be removed")]
    RequiredProduct(Product),
    #[error("cannot remove `{product}`: {} still need(s) it; remove those too", join_products(.needed_by))]
    RemoveNeeded {
        product: Product,
        needed_by: Vec<Product>,
    },
    #[error(
        "unsupported platform {host}: {} cannot be installed here; supported targets differ per \
         product (see the manifest)",
        join_products(.products)
    )]
    UnsupportedPlatform {
        host: Target,
        products: Vec<Product>,
    },
    #[error("the release has no artifact of `{product}` for {host}")]
    NoArtifact { product: Product, host: Target },
}

fn join_errors(errs: &[ManifestError]) -> String {
    errs.iter()
        .map(|e| e.to_string())
        .collect::<Vec<_>>()
        .join("; ")
}

fn join_products(ps: &[Product]) -> String {
    ps.iter()
        .map(|p| p.as_wire())
        .collect::<Vec<_>>()
        .join(", ")
}

impl PlanError {
    /// The process exit code: 2 for a request that is not well formed, 3 for a
    /// well-formed request the planner refuses.
    pub fn exit_code(&self) -> i32 {
        match self {
            PlanError::UnknownProduct(_)
            | PlanError::UnknownProfile(_)
            | PlanError::AddAndRemove(_)
            | PlanError::PrefixInvalid(_) => 2,
            _ => 3,
        }
    }
}

