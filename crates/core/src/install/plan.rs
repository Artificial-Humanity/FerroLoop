/// Every service unit the installer writes carries this line; a unit without
/// it is never overwritten.
pub const UNIT_MARKER: &str = "# generated by fl install";
/// What a marker line starts with: the marker, a space, then the release name.
const UNIT_MARKER_PREFIX: &str = "# generated by fl install ";
/// The most a probe hashes; a larger file is reported as unreadable, not read.
pub const MAX_FINGERPRINT_BYTES: u64 = 256 * 1024 * 1024;
const MARKER_WINDOW: usize = 4096;
const MAX_PREFIX_LEN: usize = 400;

// ---------------------------------------------------------------- probe

/// The reason a probe reports ([`PathState::Unreadable`]) when its caller's time budget ran
/// out before it read the path.
pub const BUDGET_EXCEEDED: &str = "time budget exceeded";

/// What a read-only look at one path found.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum PathState {
    Missing,
    Dir,
    File(FileFingerprint),
    Symlink {
        target: String,
    },
    /// A device, socket, fifo, ...
    Other,
    Unreadable {
        reason: String,
    },
}

/// The hash of a file, and whether it carries the unit marker.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct FileFingerprint {
    pub sha256: String,
    pub has_unit_marker: bool,
}

/// Whether `head` (a file's first bytes) has a line that STARTS with the unit
/// marker followed by a release name. A foreign file that merely mentions the
/// text does not count.
fn has_marker_line(head: &[u8]) -> bool {
    head.split(|b| *b == b'\n').any(|line| {
        line.len() > UNIT_MARKER_PREFIX.len() && line.starts_with(UNIT_MARKER_PREFIX.as_bytes())
    })
}

/// Hash `r` in one pass and look for a [`UNIT_MARKER`] line in its first 4 KiB.
/// More than [`MAX_FINGERPRINT_BYTES`] is an error, read no further than that.
pub fn fingerprint<R: Read>(r: R) -> std::io::Result<FileFingerprint> {
    fingerprint_capped(r, MAX_FINGERPRINT_BYTES)
}

pub(crate) fn fingerprint_capped<R: Read>(r: R, cap: u64) -> std::io::Result<FileFingerprint> {
    use sha2::{Digest, Sha256};
    let mut r = r.take(cap + 1);
    let mut total: u64 = 0;
    let mut hasher = Sha256::new();
    let mut head: Vec<u8> = Vec::with_capacity(MARKER_WINDOW);
    let mut buf = [0u8; 64 * 1024];
    loop {
        let n = r.read(&mut buf)?;
        if n == 0 {
            break;
        }
        total += n as u64;
        if total > cap {
            return Err(std::io::Error::new(
                std::io::ErrorKind::InvalidData,
                format!("file is larger than {cap} bytes"),
            ));
        }
        hasher.update(&buf[..n]);
        if head.len() < MARKER_WINDOW {
            let take = (MARKER_WINDOW - head.len()).min(n);
            head.extend_from_slice(&buf[..take]);
        }
    }
    let sha256 = hasher
        .finalize()
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect::<String>();
    let has_unit_marker = has_marker_line(&head);
    Ok(FileFingerprint {
        sha256,
        has_unit_marker,
    })
}

/// A read-only look at the host. An implementation may `lstat`, `readlink` and
/// read; it must never write.
pub trait HostProbe {
    fn probe(&self, path: &str) -> PathState;
}

/// A probe over a fixed map, for tests. Records every path asked about.
#[derive(Default)]
pub struct MapProbe {
    states: BTreeMap<String, PathState>,
    asked: RefCell<Vec<String>>,
}

impl MapProbe {
    pub fn new() -> Self {
        Self::default()
    }

    pub fn with(mut self, path: &str, state: PathState) -> Self {
        self.states.insert(path.to_string(), state);
        self
    }

    /// Every path the planner asked about, in order.
    pub fn asked(&self) -> Vec<String> {
        self.asked.borrow().clone()
    }
}

impl HostProbe for MapProbe {
    fn probe(&self, path: &str) -> PathState {
        self.asked.borrow_mut().push(path.to_string());
        self.states.get(path).cloned().unwrap_or(PathState::Missing)
    }
}

