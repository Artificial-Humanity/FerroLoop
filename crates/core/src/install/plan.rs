type Classified = Result<Disposition, (ConflictKind, String)>;

fn unreadable(reason: &str) -> (ConflictKind, String) {
    (
        ConflictKind::Unreadable,
        format!("could not be inspected: {}", display_trunc(reason)),
    )
}

fn shared_dir(state: &PathState, what: &str) -> Classified {
    match state {
        PathState::Missing => Ok(Disposition::Create),
        PathState::Dir => Ok(Disposition::Exists),
        PathState::Symlink { target } => Err((
            ConflictKind::Symlink,
            format!(
                "({what}) is a symlink to `{}` where a directory belongs; the install does not \
                 follow it, so pass the real directory as --prefix or decide about the link",
                display_trunc(target)
            ),
        )),
        PathState::File(_) | PathState::Other => Err((
            ConflictKind::TypeMismatch,
            "exists and is not a directory".into(),
        )),
        PathState::Unreadable { reason } => Err(unreadable(reason)),
    }
}

fn owned_dir(state: &PathState, owned: bool) -> Classified {
    match state {
        PathState::Missing => Ok(Disposition::Create),
        PathState::Dir if owned => Ok(Disposition::Keep),
        PathState::Dir => Err((
            ConflictKind::Foreign,
            "is a directory the receipt does not own".into(),
        )),
        PathState::Symlink { .. } => Err((
            ConflictKind::Symlink,
            "is a symlink where a directory belongs".into(),
        )),
        PathState::File(_) | PathState::Other => Err((
            ConflictKind::TypeMismatch,
            "exists and is not a directory".into(),
        )),
        PathState::Unreadable { reason } => Err(unreadable(reason)),
    }
}

fn release_file(state: &PathState, owned_sha: Option<&str>) -> Classified {
    match state {
        PathState::Missing => Ok(Disposition::Create),
        PathState::File(f) => match owned_sha {
            Some(sha) if sha == f.sha256 => Ok(Disposition::Keep),
            Some(_) => Err((
                ConflictKind::Edited,
                "is owned by the receipt but its content changed".into(),
            )),
            None => Err((
                ConflictKind::Foreign,
                "is a file the receipt does not own".into(),
            )),
        },
        PathState::Symlink { .. } => Err((
            ConflictKind::Symlink,
            "is a symlink where a file belongs".into(),
        )),
        PathState::Dir | PathState::Other => Err((
            ConflictKind::TypeMismatch,
            "exists and is not a regular file".into(),
        )),
        PathState::Unreadable { reason } => Err(unreadable(reason)),
    }
}

fn symlink(state: &PathState, desired: &str, owned_target: Option<&str>) -> Classified {
    match state {
        PathState::Missing => Ok(Disposition::Create),
        PathState::Symlink { target } => match owned_target {
            Some(t) if t == target => {
                if target == desired {
                    Ok(Disposition::Keep)
                } else {
                    Ok(Disposition::Repoint)
                }
            }
            Some(_) => Err((
                ConflictKind::Edited,
                "is an owned symlink that now points elsewhere".into(),
            )),
            None => Err((
                ConflictKind::Symlink,
                "is a symlink the receipt does not own".into(),
            )),
        },
        PathState::File(_) | PathState::Dir | PathState::Other => Err((
            ConflictKind::Foreign,
            "exists and is not a symlink the receipt owns".into(),
        )),
        PathState::Unreadable { reason } => Err(unreadable(reason)),
    }
}

fn unit_file(state: &PathState, owned: Option<(&str, &str)>, release: &str) -> Classified {
    match state {
        PathState::Missing => Ok(Disposition::Create),
        PathState::File(f) => {
            if !f.has_unit_marker {
                return Err((
                    ConflictKind::UnmarkedUnit,
                    format!(
                        "is a unit without the `{UNIT_MARKER}` marker; it is never overwritten"
                    ),
                ));
            }
            match owned {
                Some((sha, rel)) if sha == f.sha256 => {
                    if rel == release {
                        Ok(Disposition::Keep)
                    } else {
                        Ok(Disposition::Replace)
                    }
                }
                Some(_) => Err((
                    ConflictKind::Edited,
                    "is owned by the receipt but its content changed".into(),
                )),
                None => Err((
                    ConflictKind::Foreign,
                    "carries the marker but the receipt does not own it".into(),
                )),
            }
        }
        PathState::Symlink { .. } => Err((
            ConflictKind::Symlink,
            "is a symlink where a unit file belongs".into(),
        )),
        PathState::Dir | PathState::Other => Err((
            ConflictKind::TypeMismatch,
            "exists and is not a regular file".into(),
        )),
        PathState::Unreadable { reason } => Err(unreadable(reason)),
    }
}

/// `<version>+<sha12>`; a manifest with no commit is `<version>+unstamped`.
pub(crate) fn release_dir_name(manifest: &ReleaseManifest) -> String {
    let stamp = manifest
        .release
        .commit
        .as_deref()
        .map(|c| &c[..12.min(c.len())])
        .unwrap_or("unstamped");
    format!("{}+{}", manifest.release.version, stamp)
}

struct Builder<'a> {
    probe: &'a dyn HostProbe,
    receipt: Option<&'a InstallReceipt>,
    paths: Vec<PlannedPath>,
    conflicts: Vec<PlanConflict>,
    existing: Vec<String>,
}

impl Builder<'_> {
    fn finish(&mut self, path: &str, state: &PathState, result: Classified) -> Disposition {
        if !matches!(state, PathState::Missing | PathState::Dir) && self.receipt.is_none() {
            self.existing.push(path.to_string());
        }
        match result {
            Ok(d) => d,
            Err((kind, detail)) => {
                self.conflicts.push(PlanConflict {
                    path: path.to_string(),
                    kind,
                    detail: format!("{} {detail}", display_trunc(path)),
                });
                Disposition::Conflict
            }
        }
    }

    #[allow(clippy::too_many_arguments)]
    fn push(
        &mut self,
        path: String,
        kind: PlannedPathKind,
        role: PathRole,
        product: Option<Product>,
        link_target: Option<String>,
        disposition: Disposition,
    ) {
        self.paths.push(PlannedPath {
            path,
            kind,
            role,
            product,
            link_target,
            disposition,
        });
    }

    fn owned_dir(&self, path: &str) -> bool {
        self.receipt
            .and_then(|r| r.owned_path(path))
            .is_some_and(|p| p.kind == OwnedPathKind::Dir)
    }

    fn owned_file_sha(&self, path: &str) -> Option<&str> {
        self.receipt
            .and_then(|r| r.owned_path(path))
            .filter(|p| p.kind == OwnedPathKind::File)
            .and_then(|p| p.sha256.as_deref())
    }

    fn owned_link(&self, path: &str) -> Option<&str> {
        let r = self.receipt?;
        if let Some(p) = r.owned_path(path)
            && p.kind == OwnedPathKind::Symlink
        {
            return p.link_target.as_deref();
        }
        r.owned_alias(path).map(|a| a.target.as_str())
    }

    fn shared_dir(&mut self, path: String, role: PathRole) {
        let state = self.probe.probe(&path);
        let what = match role {
            PathRole::Prefix => "the install prefix itself",
            _ => "a directory under the prefix",
        };
        let d = self.finish(&path, &state, shared_dir(&state, what));
        self.push(path, PlannedPathKind::Dir, role, None, None, d);
    }

    fn dir(&mut self, path: String, role: PathRole, product: Option<Product>) {
        let state = self.probe.probe(&path);
        let r = owned_dir(&state, self.owned_dir(&path));
        let d = self.finish(&path, &state, r);
        self.push(path, PlannedPathKind::Dir, role, product, None, d);
    }

    fn file(&mut self, path: String, role: PathRole, product: Option<Product>) {
        let state = self.probe.probe(&path);
        let r = release_file(&state, self.owned_file_sha(&path));
        let d = self.finish(&path, &state, r);
        self.push(path, PlannedPathKind::File, role, product, None, d);
    }

    fn link(&mut self, path: String, target: String, role: PathRole, product: Option<Product>) {
        let state = self.probe.probe(&path);
        let r = symlink(&state, &target, self.owned_link(&path));
        let d = self.finish(&path, &state, r);
        self.push(
            path,
            PlannedPathKind::Symlink,
            role,
            product,
            Some(target),
            d,
        );
    }
}

/// Make the plan. `probe` is only asked about the paths the plan names.
///
/// Order of refusal: `--adopt`, an invalid manifest, a malformed selection, an
/// unsupported platform, a missing artifact; only then are the receipt and the
/// host looked at.
pub fn plan(
    request: &InstallRequest,
    manifest: &ReleaseManifest,
    receipt: Option<&InstallReceipt>,
    host: HostInfo,
    probe: &dyn HostProbe,
) -> Result<InstallPlan, PlanError> {
    if request.adopt {
        return Err(PlanError::AdoptNotImplemented);
    }
    manifest.validate().map_err(PlanError::InvalidManifest)?;

    // ---- selection
    for p in &request.add {
        if request.remove.contains(p) {
            return Err(PlanError::AddAndRemove(*p));
        }
    }
    if let Some(p) = request.remove.iter().find(|p| p.is_required()) {
        return Err(PlanError::RequiredProduct(*p));
    }
    let profile = request
        .profile
        .or(receipt.map(|r| r.profile))
        .unwrap_or(Profile::Minimal);
    let base: BTreeSet<Product> = match (request.profile, receipt) {
        (Some(p), _) => manifest
            .profile_products(p)
            .ok_or(PlanError::ProfileNotInManifest(p))?,
        (None, Some(r)) => r.products.iter().copied().collect(),
        (None, None) => manifest
            .profile_products(Profile::Minimal)
            .ok_or(PlanError::ProfileNotInManifest(Profile::Minimal))?,
    };
    let mut explicit: BTreeSet<Product> = base.clone();
    explicit.extend(request.add.iter().copied());
    for r in &request.remove {
        explicit.remove(r);
    }
    explicit.insert(Product::Ferroloop);

    // ---- dependency closure (real dependencies only)
    let mut set: BTreeSet<Product> = explicit.clone();
    let mut needed_by: BTreeMap<Product, BTreeSet<Product>> = BTreeMap::new();
    let mut queue: Vec<Product> = explicit.iter().copied().collect();
    while let Some(p) = queue.pop() {
        let entry = manifest.product(p).ok_or(PlanError::NotInManifest(p))?;
        for d in entry.required_products() {
            needed_by.entry(d).or_default().insert(p);
            if set.insert(d) {
                queue.push(d);
            }
        }
    }
    if let Some(p) = request.remove.iter().find(|p| set.contains(p)) {
        return Err(PlanError::RemoveNeeded {
            product: *p,
            needed_by: needed_by
                .get(p)
                .map(|s| s.iter().copied().collect())
                .unwrap_or_default(),
        });
    }

    // ---- platform and artifacts, before anything on the host is looked at
    let target = host.target();
    let unsupported: Vec<Product> = set
        .iter()
        .copied()
        .filter(|p| {
            manifest
                .product(*p)
                .is_none_or(|e| !e.targets.contains(&target))
        })
        .collect();
    if !unsupported.is_empty() {
        return Err(PlanError::UnsupportedPlatform {
            host: target,
            products: unsupported,
        });
    }
    let mut artifacts: BTreeMap<String, PlannedArtifact> = BTreeMap::new();
    if manifest.release.kind == ReleaseKind::Release {
        for p in &set {
            let a = manifest
                .artifacts
                .iter()
                .find(|a| a.target == target && a.provides.iter().any(|s| s == p.as_wire()))
                .ok_or(PlanError::NoArtifact {
                    product: *p,
                    host: target,
                })?;
            artifacts.insert(
                a.id.clone(),
                PlannedArtifact {
                    id: a.id.clone(),
                    file: a.file.clone(),
                    sha256: a.sha256.clone(),
                    size: a.size,
                },
            );
        }
    }

    // ---- product explanations
    let products: Vec<SelectedProduct> = set
        .iter()
        .map(|&p| {
            let origin = if p.is_required() {
                Origin::Required
            } else if base.contains(&p) {
                Origin::Selected
            } else if request.add.contains(&p) {
                Origin::Added
            } else {
                Origin::Dependency
            };
            let mut because = Vec::new();
            if origin == Origin::Dependency {
                if p.is_hidden() {
                    because.push("hidden default dependency".to_string());
                }
                for by in needed_by.get(&p).into_iter().flatten() {
                    because.push(format!("included because {by} needs {p}"));
                }
            }
            SelectedProduct {
                id: p,
                title: p.title(),
                origin,
                hidden: p.is_hidden(),
                included_because: because,
            }
        })
        .collect();
    let not_installed: Vec<NotInstalled> = Product::ALL
        .iter()
        .filter(|p| !set.contains(p))
        .map(|&p| NotInstalled {
            product: p,
            cli: format!("{p} is not installed (fl install --add {p})"),
            hub: format!("404 {{\"error\":\"module_not_installed\",\"module\":\"{p}\"}}"),
        })
        .collect();
    let mut module_routes = Vec::new();
    for &consumer in &set {
        if let Some(e) = manifest.product(consumer) {
            for m in e.optional_products() {
                if !set.contains(&m) {
                    module_routes.push(ModuleRoute {
                        module: m,
                        consumer,
                        response: "404 module_not_installed".into(),
                    });
                }
            }
        }
    }
    module_routes.sort_by_key(|r| (r.module, r.consumer));

    // ---- paths (read-only probing)
    let layout = &request.layout;
    let name = release_dir_name(manifest);
    let releases = join(&layout.prefix, "releases");
    let release_dir = join(&releases, &name);
    let mut b = Builder {
        probe,
        receipt,
        paths: Vec::new(),
        conflicts: Vec::new(),
        existing: Vec::new(),
    };
    b.shared_dir(layout.prefix.clone(), PathRole::Prefix);
    b.shared_dir(releases.clone(), PathRole::Releases);
    b.dir(release_dir.clone(), PathRole::Release, None);
    let mut seen = BTreeSet::new();
    for &p in &set {
        let Some(e) = manifest.product(p) else {
            continue;
        };
        let mut files: Vec<_> = e.files.iter().collect();
        files.sort_by(|a, b| a.path.cmp(&b.path));
        for f in files {
            let path = join(&release_dir, &f.path);
            if !seen.insert(path.clone()) {
                continue;
            }
            match f.kind {
                FileKind::AssetDir => b.dir(path, PathRole::ReleaseFile, Some(p)),
                FileKind::Binary | FileKind::UnitTemplate => {
                    b.file(path, PathRole::ReleaseFile, Some(p));
                }
            }
        }
    }
    b.link(
        join(&layout.prefix, "current"),
        format!("releases/{name}"),
        PathRole::Current,
        None,
    );
    let receipt_path = join(&layout.prefix, "receipt.json");
    b.push(
        receipt_path.clone(),
        PlannedPathKind::File,
        PathRole::Receipt,
        None,
        None,
        if receipt.is_some() {
            Disposition::Update
        } else {
            Disposition::Create
        },
    );
    b.push(
        join(&layout.prefix, "install.lock"),
        PlannedPathKind::File,
        PathRole::Lock,
        None,
        None,
        Disposition::Create,
    );
    b.link(
        join(&layout.bin_dir, "fl"),
        join(&layout.prefix, "current/bin/fl"),
        PathRole::Launcher,
        Some(Product::Ferroloop),
    );
    let mut aliases: BTreeMap<String, Product> = BTreeMap::new();
    for &p in &set {
        if let Some(e) = manifest.product(p) {
            for a in &e.aliases {
                aliases.entry(a.clone()).or_insert(p);
            }
        }
    }
    for (alias, p) in aliases {
        b.link(
            join(&layout.bin_dir, &alias),
            "fl".to_string(),
            PathRole::Alias,
            Some(p),
        );
    }

    // ---- separate planned actions
    let mut notes: Vec<String> = Vec::new();
    let mut actions: Vec<PlannedAction> = Vec::new();
    for &p in &set {
        let Some(e) = manifest.product(p) else {
            continue;
        };
        for a in &e.actions {
            let id = format!("{p}:{}:{}", a.kind.as_wire(), a.subject);
            if !a.planned_in.is_empty() && !a.planned_in.contains(&profile) {
                notes.push(format!("action {id} is not planned in profile {profile}"));
                continue;
            }
            if !a.os.is_empty() && !a.os.contains(&host.os) {
                notes.push(format!(
                    "action {id} is not planned: it does not apply on {}",
                    host.os.as_wire()
                ));
                continue;
            }
            let (path, disposition) = if a.kind == ActionKind::RegisterService {
                let path = join(&layout.unit_dir, &a.subject);
                let state = b.probe.probe(&path);
                let owned = receipt
                    .and_then(|r| r.owned_unit(&path))
                    .map(|u| (u.sha256.as_str(), u.release.as_str()));
                let r = unit_file(&state, owned, &name);
                let d = b.finish(&path, &state, r);
                (Some(path), Some(d))
            } else {
                (None, None)
            };
            actions.push(PlannedAction {
                id,
                kind: a.kind,
                product: p,
                subject: a.subject.clone(),
                approval: if a.by_profile.contains(&profile) {
                    Approval::ByProfile
                } else {
                    Approval::RequiresApproval
                },
                path,
                disposition,
                detail: a.detail.clone(),
            });
        }
    }
    actions.sort_by(|x, y| (x.kind, &x.id).cmp(&(y.kind, &y.id)));

    // ---- notes
    let management = if receipt.is_some() {
        Management::Managed
    } else {
        Management::Unmanaged
    };
    if manifest.release.kind == ReleaseKind::SourceBuild {
        notes.push(
            "this manifest lists no signed artifacts: the files above would come from a \
             reviewed-commit source build, which is not implemented in this release"
                .into(),
        );
    }
    match receipt {
        None => notes.push(format!(
            "no install receipt at {receipt_path}: existing files and services are UNMANAGED; \
             nothing is claimed, and adopting them (--adopt) is not implemented in this release"
        )),
        Some(r) => {
            if r.release.name != name {
                notes.push(format!(
                    "the receipt records release {}; this plan activates {name}",
                    r.release.name
                ));
            }
            let dropped: Vec<&str> = r
                .products
                .iter()
                .filter(|p| !set.contains(p))
                .map(|p| p.as_wire())
                .collect();
            if !dropped.is_empty() {
                notes.push(format!(
                    "the receipt owns {} which this selection drops; removal is not planned in \
                     this release",
                    dropped.join(", ")
                ));
            }
        }
    }
    notes.push(
        "a plain install writes verified files and the receipt only; every action above is a \
         separate step"
            .into(),
    );

    let status = if b.conflicts.is_empty() {
        PlanStatus::Ready
    } else {
        PlanStatus::NeedsDecision
    };
    let mut existing = b.existing;
    existing.sort();
    existing.dedup();
    Ok(InstallPlan {
        schema_version: PLAN_SCHEMA_VERSION,
        release: PlanRelease {
            version: manifest.release.version.clone(),
            name,
            kind: manifest.release.kind,
        },
        compat: manifest.compat,
        host,
        profile,
        management,
        status,
        layout: layout.clone(),
        receipt_path,
        products,
        not_installed,
        module_routes,
        artifacts: artifacts.into_values().collect(),
        paths: b.paths,
        actions,
        conflicts: b.conflicts,
        unmanaged_existing: existing,
        notes,
    })
}

impl InstallPlan {
    /// The plan as pretty JSON with a trailing newline.
    pub fn to_json(&self) -> String {
        let mut out = serde_json::to_string_pretty(self).expect("plan serializes");
        out.push('\n');
        out
    }

    /// The plan for a person. Same inputs, same bytes.
    pub fn render_text(&self) -> String {
        let mut o = String::new();
        let mut line = |s: String| {
            o.push_str(&s);
            o.push('\n');
        };
        line("fl install plan (dry run): nothing was changed".into());
        line(format!(
            "release   {} ({})",
            self.release.name,
            self.release.kind.as_wire()
        ));
        line(format!(
            "host      {}/{}",
            self.host.os.as_wire(),
            self.host.arch.as_wire()
        ));
        line(format!("profile   {}", self.profile));
        line(format!(
            "state     {}",
            match self.management {
                Management::Managed => "managed (install receipt found)",
                Management::Unmanaged => "unmanaged (no install receipt)",
            }
        ));
        line(format!("status    {}", self.status.as_wire()));
        line(format!("prefix    {}", self.layout.prefix));
        line(format!("launcher  {}/fl", self.layout.bin_dir));
        line(format!(
            "compat    protocol {}, store formats {}..={}",
            self.compat.protocol_major, self.compat.store_format_min, self.compat.store_format_max
        ));
        line(String::new());
        line(format!("products ({})", self.products.len()));
        for p in &self.products {
            line(format!("  {:<11} {}", p.id.as_wire(), p.origin.as_wire()));
            for why in &p.included_because {
                line(format!("              {why}"));
            }
        }
        if !self.not_installed.is_empty() {
            line(String::new());
            line("not installed".into());
            for n in &self.not_installed {
                line(format!("  {}", n.cli));
            }
        }
        if !self.module_routes.is_empty() {
            line(String::new());
            line("module routes (hub answers 404 module_not_installed)".into());
            for r in &self.module_routes {
                line(format!("  {} for {}", r.module, r.consumer));
            }
        }
        if !self.artifacts.is_empty() {
            line(String::new());
            line("artifacts".into());
            for a in &self.artifacts {
                line(format!("  {} {} sha256:{}", a.id, a.file, a.sha256));
            }
        }
        line(String::new());
        line("paths".into());
        for p in &self.paths {
            let mut s = format!("  {:<8} {}", p.disposition.as_wire(), p.path);
            if let Some(t) = &p.link_target {
                s.push_str(&format!(" -> {t}"));
            }
            line(s);
        }
        line(String::new());
        line("planned actions (none runs as part of a plain install)".into());
        if self.actions.is_empty() {
            line("  none".into());
        }
        for a in &self.actions {
            let mut s = format!("  [{}] {}", a.approval.as_wire(), a.id);
            if let (Some(p), Some(d)) = (&a.path, a.disposition) {
                s.push_str(&format!(" at {p} ({})", d.as_wire()));
            }
            if !a.detail.is_empty() {
                s.push_str(&format!(": {}", a.detail));
            }
            line(s);
        }
        if !self.conflicts.is_empty() {
            line(String::new());
            line(
                "conflicts (each needs an explicit decision; nothing is overwritten silently)"
                    .into(),
            );
            for c in &self.conflicts {
                line(format!("  {}: {}", c.kind.as_wire(), c.detail));
            }
        }
        if !self.unmanaged_existing.is_empty() {
            line(String::new());
            line("unmanaged state found (not claimed)".into());
            for p in &self.unmanaged_existing {
                line(format!("  {p}"));
            }
        }
        line(String::new());
        line("notes".into());
        for n in &self.notes {
            line(format!("  {n}"));
        }
        o
    }
}

impl fmt::Display for InstallPlan {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.render_text())
    }
}
