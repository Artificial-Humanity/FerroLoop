/// Where an install lives, as the plan displays it. The default keeps `~`
/// unexpanded, so no plan carries a home directory unless the caller gave one.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Layout {
    pub prefix: String,
    pub bin_dir: String,
    pub unit_dir: String,
}

/// Directories no install prefix may be: `/` and the places a home or a
/// system sits.
const FORBIDDEN_EXACT: &[&str] = &[
    "/", "/home", "/root", "/var", "/opt", "/tmp", "/srv", "/mnt", "/media", "/run", "/Users",
];
/// Trees an install never writes into: a system-wide install is a non-goal.
const FORBIDDEN_TREES: &[&str] = &[
    "/usr",
    "/etc",
    "/bin",
    "/sbin",
    "/lib",
    "/lib32",
    "/lib64",
    "/boot",
    "/sys",
    "/proc",
    "/dev",
    "/System",
    "/Library",
    "/Applications",
    "/private/etc",
];

fn normalize_abs(raw: &str, what: &str) -> Result<String, PlanError> {
    let bad =
        |why: &str| PlanError::PrefixInvalid(format!("{what} `{}` {why}", display_trunc(raw)));
    if raw.is_empty() {
        return Err(bad("is empty"));
    }
    if raw.len() > MAX_PREFIX_LEN {
        return Err(bad("is too long"));
    }
    if raw.contains('\0') {
        return Err(bad("contains a NUL byte"));
    }
    if !raw.starts_with('/') {
        return Err(bad("is not absolute"));
    }
    let trimmed = raw.trim_end_matches('/');
    let norm = if trimmed.is_empty() { "/" } else { trimmed };
    for seg in norm.split('/').skip(1).filter(|_| norm != "/") {
        if seg == ".." || seg == "." {
            return Err(bad("has a `.` or `..` segment"));
        }
        if seg.is_empty() {
            return Err(bad("has an empty segment"));
        }
    }
    Ok(norm.to_string())
}

fn display_trunc(s: &str) -> String {
    s.chars().filter(|c| !c.is_control()).take(80).collect()
}

fn forbidden_tree(norm: &str) -> bool {
    FORBIDDEN_TREES
        .iter()
        .any(|t| norm == *t || norm.starts_with(&format!("{t}/")))
}

pub(crate) fn join(base: &str, rel: &str) -> String {
    format!("{}/{}", base.trim_end_matches('/'), rel)
}

/// The layout a command works on: `--prefix`, then `$FL_INSTALL_ROOT`, then the per-user
/// default. Pure: the caller passes the environment's value.
pub fn resolve_layout(
    prefix: Option<&std::path::Path>,
    root: Option<std::ffi::OsString>,
) -> Result<Layout, PlanError> {
    let utf8 = |p: &std::ffi::OsStr, what: &str| {
        p.to_str()
            .map(str::to_owned)
            .ok_or_else(|| PlanError::PrefixInvalid(format!("{what} is not valid UTF-8")))
    };
    if let Some(p) = prefix {
        return Layout::explicit(&utf8(p.as_os_str(), "--prefix")?);
    }
    match root.filter(|r| !r.is_empty()) {
        Some(r) => Layout::under_root(&utf8(&r, "$FL_INSTALL_ROOT")?),
        None => Ok(Layout::user_default()),
    }
}

impl Layout {
    /// `~/.local/share/fl`, `~/.local/bin`, `~/.config/systemd/user`; nothing
    /// is expanded.
    pub fn user_default() -> Self {
        Self {
            prefix: "~/.local/share/fl".into(),
            bin_dir: "~/.local/bin".into(),
            unit_dir: "~/.config/systemd/user".into(),
        }
    }

    /// The default layout under an isolated root (`FL_INSTALL_ROOT`): the
    /// root plays the part of the home directory.
    pub fn under_root(root: &str) -> Result<Self, PlanError> {
        let root = normalize_abs(root, "install root")?;
        if root == "/" || forbidden_tree(&root) {
            return Err(PlanError::PrefixForbidden(display_trunc(&root)));
        }
        Ok(Self {
            prefix: join(&root, ".local/share/fl"),
            bin_dir: join(&root, ".local/bin"),
            unit_dir: join(&root, ".config/systemd/user"),
        })
    }

    /// A self-contained layout under an explicit prefix: launcher in
    /// `<prefix>/bin`, units in `<prefix>/units`.
    pub fn explicit(prefix: &str) -> Result<Self, PlanError> {
        let prefix = normalize_abs(prefix, "prefix")?;
        let depth = prefix.split('/').count() - 1;
        let is_home_dir =
            depth == 2 && (prefix.starts_with("/home/") || prefix.starts_with("/Users/"));
        if FORBIDDEN_EXACT.contains(&prefix.as_str()) || forbidden_tree(&prefix) || is_home_dir {
            return Err(PlanError::PrefixForbidden(display_trunc(&prefix)));
        }
        Ok(Self {
            bin_dir: join(&prefix, "bin"),
            unit_dir: join(&prefix, "units"),
            prefix,
        })
    }
}

